def plot_confusion_matrix(
    targets: List[int],
    preds: List[int],
    num_classes: int,
    dataset_name: str,
    model_name: str,
    save_dir: str = OUT_DIR,
):
    cm = confusion_matrix(targets, preds, labels=list(range(num_classes)))
    cm_norm = cm.astype(float) / (cm.sum(axis=1, keepdims=True) + 1e-8)

    fig_size = max(6, num_classes // 2)
    fig, ax = plt.subplots(figsize=(fig_size, fig_size - 1))
    sns.heatmap(
        cm_norm * 100, annot=(num_classes <= 10), fmt=".1f",
        cmap="Blues", ax=ax, vmin=0, vmax=100,
        xticklabels=range(num_classes), yticklabels=range(num_classes),
    )
    ax.set_title(f"Confusion Matrix (%) – {dataset_name} / {model_name}")
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    plt.tight_layout()
    path = os.path.join(save_dir, f"cm_{dataset_name}_{model_name}.png")
    plt.savefig(path, dpi=120)
    plt.close()
    return path


def plot_roc_curves(
    targets: List[int],
    probs: List[np.ndarray],
    num_classes: int,
    dataset_name: str,
    model_name: str,
    save_dir: str = OUT_DIR,
):
    y_true = label_binarize(targets, classes=list(range(num_classes)))
    y_prob = np.array(probs)

    plt.figure(figsize=(8, 6))
    for i in range(num_classes):
        if y_true[:, i].sum() == 0:
            continue
        fpr, tpr, _ = roc_curve(y_true[:, i], y_prob[:, i])
        roc_auc = auc(fpr, tpr)
        plt.plot(fpr, tpr, alpha=0.5, lw=1, label=f"C{i} (AUC={roc_auc:.2f})")
    plt.plot([0, 1], [0, 1], "k--")
    plt.xlabel("FPR")
    plt.ylabel("TPR")
    plt.title(f"ROC Curves – {dataset_name} / {model_name}")
    plt.legend(fontsize=6, loc="lower right", ncol=2)
    plt.tight_layout()
    path = os.path.join(save_dir, f"roc_{dataset_name}_{model_name}.png")
    plt.savefig(path, dpi=120)
    plt.close()
    return path


def plot_training_curves(
    history: Dict,
    dataset_name: str,
    model_name: str,
    save_dir: str = OUT_DIR,
):
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    axes[0].plot(history["train_loss"], label="Train")
    axes[0].plot(history["val_loss"],   label="Val")
    axes[0].set_title("Loss")
    axes[0].set_xlabel("Epoch")
    axes[0].legend()

    axes[1].plot(history["train_acc"], label="Train")
    axes[1].plot(history["val_acc"],   label="Val")
    axes[1].set_title("Accuracy")
    axes[1].set_xlabel("Epoch")
    axes[1].legend()

    plt.suptitle(f"Training Curves – {dataset_name} / {model_name}")
    plt.tight_layout()
    path = os.path.join(save_dir, f"curves_{dataset_name}_{model_name}.png")
    plt.savefig(path, dpi=120)
    plt.close()
    return path


def plot_summary_heatmap(
    summary_rows: List[Dict],
    save_dir: str = OUT_DIR,
):
    """Side-by-side heatmaps of OA / AA / Kappa for all models × datasets."""
    datasets_seen = sorted({r["dataset"] for r in summary_rows})
    models_seen   = [m for m in MODEL_NAMES if any(r["model"] == m for r in summary_rows)]

    for metric in ("OA", "AA", "Kappa"):
        mat = np.full((len(models_seen), len(datasets_seen)), np.nan)
        for r in summary_rows:
            ri = models_seen.index(r["model"])
            ci = datasets_seen.index(r["dataset"])
            mat[ri, ci] = r[metric]

        fig, ax = plt.subplots(figsize=(len(datasets_seen) * 2 + 2, len(models_seen) + 1))
        sns.heatmap(
            mat, annot=True, fmt=".3f", cmap="YlGnBu",
            xticklabels=datasets_seen, yticklabels=models_seen,
            ax=ax, vmin=0, vmax=1,
        )
        ax.set_title(f"Benchmark – {metric}")
        plt.tight_layout()
        path = os.path.join(save_dir, f"benchmark_{metric.lower()}.png")
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"Saved → {path}")


