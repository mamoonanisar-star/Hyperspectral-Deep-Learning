def generate_synthetic_dataset(dataset_name: str, seed: int = 42) -> Tuple[np.ndarray, np.ndarray]:
    """Generate (H, W, B) data and (H, W) gt arrays mimicking a real dataset."""
    p = DATASET_PARAMS[dataset_name]
    nc, nb, H, W = p["nc"], p["nb"], p["h"], p["w"]
    rng = np.random.default_rng(seed)

    data = np.zeros((H, W, nb), dtype=np.float32)
    gt   = np.zeros((H, W), dtype=np.int32)

    ph = H // nc
    for cls in range(nc):
        rs = cls * ph
        re = (cls + 1) * ph if cls < nc - 1 else H
        mean_vec = rng.uniform(0.05, 0.6, nb).astype(np.float32)
        noise = rng.normal(0, 0.03, (re - rs, W, nb)).astype(np.float32)
        data[rs:re, :, :] = np.clip(mean_vec + noise, 0.0, 1.0)
        gt[rs:re, :] = cls + 1   # 1-based

    return data, gt


# ---------------------------------------------------------------------------
# Patch extraction + normalisation
# ---------------------------------------------------------------------------

def extract_patches(
    data: np.ndarray,
    gt: np.ndarray,
    patch_size: int = PATCH_SIZE,
) -> Tuple[torch.Tensor, torch.Tensor]:
    pad = patch_size // 2

    # normalise
    h, w, b = data.shape
    flat = data.reshape(-1, b).astype(np.float32)
    flat = (flat - flat.mean(0)) / (flat.std(0) + 1e-8)
    data_n = flat.reshape(h, w, b)

    padded = np.pad(data_n, ((pad, pad), (pad, pad), (0, 0)), mode="reflect")
    ys, xs = np.where(gt > 0)

    patches, labels = [], []
    for y, x in zip(ys, xs):
        p = padded[y: y + patch_size, x: x + patch_size, :].transpose(2, 0, 1)
        patches.append(p)
        labels.append(int(gt[y, x]) - 1)

    X = torch.tensor(np.array(patches, dtype=np.float32))
    y = torch.tensor(labels, dtype=torch.long)
    return X, y


def make_loaders(
    X: torch.Tensor,
    y: torch.Tensor,
    batch_size: int = BATCH_SIZE,
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    idx = np.arange(len(y))
    i_tv, i_te = train_test_split(idx, test_size=0.10, stratify=y.numpy(), random_state=42)
    i_tr, i_va = train_test_split(i_tv, test_size=0.111, stratify=y[i_tv].numpy(), random_state=42)

    def loader(ind, shuffle):
        return DataLoader(TensorDataset(X[ind], y[ind]),
                          batch_size=batch_size, shuffle=shuffle, num_workers=0)

    return loader(i_tr, True), loader(i_va, False), loader(i_te, False)


# ---------------------------------------------------------------------------
# Training & evaluation
# ---------------------------------------------------------------------------

def train_and_eval(
    model: nn.Module,
    train_loader: DataLoader,
    val_loader: DataLoader,
    test_loader: DataLoader,
    num_classes: int,
    epochs: int = EPOCHS,
    device: str = "cpu",
) -> Tuple[Dict, Dict]:
    model = model.to(device)
    opt   = optim.Adam(model.parameters(), lr=1e-3, weight_decay=1e-4)
    sched = optim.lr_scheduler.CosineAnnealingLR(opt, T_max=epochs)
    crit  = nn.CrossEntropyLoss()

    history: Dict[str, List[float]] = {
        "train_loss": [], "val_loss": [], "train_acc": [], "val_acc": []}

    for epoch in range(epochs):
        model.train()
        tl, tc, tt = 0.0, 0, 0
        for xb, yb in train_loader:
            xb, yb = xb.to(device), yb.to(device)
            opt.zero_grad()
            out = model(xb)
            loss = crit(out, yb)
            loss.backward()
            opt.step()
            tl += loss.item() * xb.size(0)
            tc += (out.argmax(1) == yb).sum().item()
            tt += xb.size(0)
        sched.step()

        model.eval()
        vl, vc, vt = 0.0, 0, 0
        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(device), yb.to(device)
                out = model(xb)
                vl += crit(out, yb).item() * xb.size(0)
                vc += (out.argmax(1) == yb).sum().item()
                vt += xb.size(0)

        history["train_loss"].append(tl / tt)
        history["val_loss"].append(vl / vt)
        history["train_acc"].append(tc / tt)
        history["val_acc"].append(vc / vt)

    # ---- test evaluation ----
    model.eval()
    all_preds, all_targets, all_probs = [], [], []
    with torch.no_grad():
        for xb, yb in test_loader:
            xb = xb.to(device)
            out = model(xb)
            probs = torch.softmax(out, dim=1).cpu().numpy()
            preds = out.argmax(1).cpu().numpy()
            all_preds.extend(preds)
            all_targets.extend(yb.numpy())
            all_probs.extend(probs)

    oa = accuracy_score(all_targets, all_preds)
    kappa = cohen_kappa_score(all_targets, all_preds)
    unique_classes = sorted(set(all_targets))
    per_class_acc = []
    for c in unique_classes:
        mask = [t == c for t in all_targets]
        if sum(mask) == 0:
            continue
        per_class_acc.append(accuracy_score(
            [t for t, m in zip(all_targets, mask) if m],
            [p for p, m in zip(all_preds, mask) if m],
        ))
    aa = float(np.mean(per_class_acc)) if per_class_acc else 0.0

    metrics = {
        "OA": oa, "AA": aa, "Kappa": kappa,
        "preds": all_preds, "targets": all_targets, "probs": all_probs,
    }
    return history, metrics


