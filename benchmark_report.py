"""
Project 4: Benchmark Comparison Report
========================================
Runs all six model types (ResNet, ViT, 3D-CNN, Hybrid, U-Net, FCN) on up to
three datasets and collects:
  • OA  – Overall Accuracy
  • AA  – Average (per-class) Accuracy
  • κ   – Cohen's Kappa coefficient

Then generates:
  • A per-dataset confusion matrix for every model
  • ROC curves (one-vs-rest) for classification models
  • Training-curve plots (loss & accuracy / IoU)
  • A summary table printed to stdout and saved as CSV

Usage
-----
    python benchmark_report.py

The script trains lightweight versions of every model on synthetic data so it
runs without GPU or internet access. Pass `real_data=True` to load the actual
hyperspectral datasets if you have previously downloaded them.

For a Jupyter Notebook version: open benchmark_report.ipynb (generated by
running this script with --notebook flag).
"""

