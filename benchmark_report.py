def run_benchmark(
    datasets: Optional[List[str]] = None,
    models: Optional[List[str]] = None,
    epochs: int = EPOCHS,
    real_data: bool = False,
):
    """
    Parameters
    ----------
    datasets  : subset of ['indian_pines', 'pavia_university', 'salinas']
    models    : subset of MODEL_NAMES
    epochs    : training epochs per model
    real_data : if True, attempt to load real .mat files from datasets/
    """
    if datasets is None:
        datasets = DATASETS
    if models is None:
        models = MODEL_NAMES

    os.makedirs(OUT_DIR, exist_ok=True)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"\n{'='*65}")
    print(f"  Benchmark Comparison Report")
    print(f"  Device: {device}  |  Epochs: {epochs}")
    print(f"  Datasets: {datasets}")
    print(f"  Models  : {models}")
    print(f"{'='*65}\n")

    summary_rows = []

    for ds in datasets:
        print(f"\n{'─'*65}")
        print(f"  Dataset: {ds.upper()}")
        print(f"{'─'*65}")

        # ---- load or synthesise data ----
        if real_data:
            try:
                from scipy.io import loadmat
                params = DATASET_PARAMS[ds]
                dkeys = {
                    "indian_pines":     ("datasets/indian_pines_data.mat",  "indian_pines_corrected",
                                         "datasets/indian_pines_gt.mat",    "indian_pines_gt"),
                    "pavia_university": ("datasets/pavia_university_data.mat", "paviaU",
                                         "datasets/pavia_university_gt.mat",  "paviaU_gt"),
                    "salinas":          ("datasets/salinas_data.mat",  "salinas_corrected",
                                         "datasets/salinas_gt.mat",    "salinas_gt"),
                }
                dp, dk, gp, gk = dkeys[ds]
                data = loadmat(dp)[dk].astype(np.float32)
                gt   = loadmat(gp)[gk].astype(np.int32).squeeze()
                print(f"  Loaded real data: {data.shape}")
            except Exception as e:
                print(f"  [WARN] Could not load real data ({e}); using synthetic fallback.")
                data, gt = generate_synthetic_dataset(ds)
        else:
            data, gt = generate_synthetic_dataset(ds)
            print(f"  Using synthetic data: {data.shape}")

        nb = data.shape[-1]
        nc = len(np.unique(gt[gt > 0]))

        # ---- patches ----
        X, y = extract_patches(data, gt, patch_size=PATCH_SIZE)
        train_loader, val_loader, test_loader = make_loaders(X, y)
        print(f"  Patches: {X.shape},  Classes: {nc}")

        for mname in models:
            print(f"\n  → {mname}", end="", flush=True)
            t0 = time.time()

            model = MODEL_FACTORY[mname](nb, nc)
            history, metrics = train_and_eval(
                model, train_loader, val_loader, test_loader,
                num_classes=nc, epochs=epochs, device=device,
            )

            elapsed = time.time() - t0
            print(f"  OA={metrics['OA']*100:.1f}%  AA={metrics['AA']*100:.1f}%"
                  f"  κ={metrics['Kappa']:.4f}  [{elapsed:.0f}s]")

            # Plots
            plot_confusion_matrix(metrics["targets"], metrics["preds"], nc, ds, mname)
            plot_roc_curves(metrics["targets"], metrics["probs"], nc, ds, mname)
            plot_training_curves(history, ds, mname)

            summary_rows.append({
                "dataset": ds,
                "model":   mname,
                "OA":      metrics["OA"],
                "AA":      metrics["AA"],
                "Kappa":   metrics["Kappa"],
                "train_time_s": round(elapsed, 1),
            })

    # ---- summary ----
    print(f"\n{'='*75}")
    print(f"{'Dataset':<22} {'Model':<10} {'OA (%)':>8} {'AA (%)':>8} {'Kappa':>8} {'Time(s)':>8}")
    print(f"{'─'*75}")
    for r in summary_rows:
        print(f"{r['dataset']:<22} {r['model']:<10} {r['OA']*100:>8.2f}"
              f" {r['AA']*100:>8.2f} {r['Kappa']:>8.4f} {r['train_time_s']:>8.1f}")
    print(f"{'='*75}")

    plot_summary_heatmap(summary_rows)
    csv_path = save_csv(summary_rows)

    print(f"\n[INFO] Project 4 complete. All outputs saved to {OUT_DIR}/")
    return summary_rows


