def save_csv(summary_rows: List[Dict], save_dir: str = OUT_DIR):
    path = os.path.join(save_dir, "benchmark_results.csv")
    fields = ["dataset", "model", "OA", "AA", "Kappa", "train_time_s"]
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in summary_rows:
            w.writerow({k: round(r[k], 6) if isinstance(r[k], float) else r[k] for k in fields})
    print(f"\nCSV saved → {path}")
    return path


